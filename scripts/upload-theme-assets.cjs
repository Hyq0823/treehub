#!/usr/bin/env node
// Admin-side tool only. Never bundle cloud credentials into the mini-program.
const fs = require('node:fs');
const path = require('node:path');
const { createRequire } = require('node:module');
const root = path.resolve(__dirname, '..');
const config = require('../config/theme-assets.js');
const args = process.argv.slice(2);
const value = flag => args.includes(flag) ? args[args.indexOf(flag) + 1] : '';
const source = path.resolve(value('--source') || path.join(root, '..', 'treehub-cloud-assets'));
const manifestPath = value('--import-manifest');
const dryRun = args.includes('--dry-run');

function validate(files) {
  for (const id of Object.keys(config.files)) {
    const fileId = files && files[id];
    if (typeof fileId !== 'string' || !fileId.startsWith(`cloud://${config.environmentId}.`)) throw new Error(`缺少素材 ${id} 在当前环境的有效云文件 ID`);
  }
}
function saveConfig(files) {
  validate(files);
  const next = { version: 1, environmentId: config.environmentId, files };
  const content = '// Generated by scripts/upload-theme-assets.cjs. No secrets or binary assets.\nmodule.exports = ' + JSON.stringify(next, null, 2) + ';\n';
  const temporary = path.join(root, 'config/theme-assets.js.tmp');
  fs.writeFileSync(temporary, content);
  fs.renameSync(temporary, path.join(root, 'config/theme-assets.js'));
}
async function main() {
  if (manifestPath) {
    const manifest = JSON.parse(fs.readFileSync(path.resolve(manifestPath), 'utf8'));
    if (manifest.environmentId !== config.environmentId) throw new Error('素材清单不属于当前云环境');
    if (!dryRun) saveConfig(manifest.files);
    else validate(manifest.files);
    console.log(dryRun ? 'Cloud manifest validated.' : 'Cloud IDs imported. Recompile the mini-program.');
    return;
  }
  const uploads = Object.keys(config.files).map(id => ({ id, cloudPath: `themes/v1/${id}.webp`, localPath: path.join(source, 'themes/v1', `${id}.webp`) }));
  const missing = uploads.filter(item => !fs.existsSync(item.localPath));
  if (missing.length) throw new Error('缺少美术资源：' + missing.map(item => item.id).join(', '));
  if (dryRun) {
    uploads.forEach(item => console.log(`${item.cloudPath} (${fs.statSync(item.localPath).size} bytes)`));
    console.log('Dry run complete. No files uploaded.');
    return;
  }
  let sdk;
  try {
    const sdkRoot = value('--sdk-root');
    sdk = sdkRoot ? createRequire(path.join(path.resolve(sdkRoot), 'package.json'))('@cloudbase/node-sdk') : require('@cloudbase/node-sdk');
  } catch (_) { throw new Error('请在仓库外安装 @cloudbase/node-sdk，并通过 --sdk-root 指向该目录；参考 docs/素材与发布.md'); }
  const secretId = process.env.CLOUDBASE_SECRET_ID;
  const secretKey = process.env.CLOUDBASE_SECRET_KEY;
  if (!secretId || !secretKey) throw new Error('当前终端未配置云开发管理员凭据；也可在控制台上传后用 --import-manifest 导入文件 ID。');
  const app = sdk.init({ env: config.environmentId, secretId, secretKey, sessionToken: process.env.CLOUDBASE_SESSION_TOKEN });
  const files = {};
  for (const item of uploads) {
    const result = await app.uploadFile({ cloudPath: item.cloudPath, fileContent: fs.createReadStream(item.localPath) });
    if (!result || !result.fileID || !result.fileID.startsWith('cloud://')) throw new Error(`${item.id} 上传失败，配置未覆盖`);
    files[item.id] = result.fileID;
    console.log(`Uploaded ${item.id}`);
  }
  const manifest = { environmentId: config.environmentId, files };
  fs.writeFileSync(path.join(source, 'cloud-manifest.json'), JSON.stringify(manifest, null, 2) + '\n');
  saveConfig(files);
  console.log('Nine themes and the companion atlas uploaded; cloud IDs saved. No binary added to the mini-program.');
}
main().catch(error => { console.error(error.message); process.exitCode = 1; });
