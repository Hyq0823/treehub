#!/usr/bin/env node
// Development only: keep hall resume metadata aligned without loading quizzes.
const fs = require('node:fs');
const path = require('node:path');
const { TEST_VERSION } = require('../utils/scoring.js');
function signature(test) {
  const source = JSON.stringify(test.questions);
  let value = 2166136261;
  for (let index = 0; index < source.length; index++) {
    value ^= source.charCodeAt(index);
    value = Math.imul(value, 16777619);
  }
  return (value >>> 0).toString(16);
}
const target = path.resolve(__dirname, '../data/draft-manifest.js');
function manifestContents(tests) {
  if (!tests) {
    const imported = require('../data/tests/index.js');
    tests = imported.default || imported;
  }
  const entries = tests.map(test => `  ${JSON.stringify(test.id)}: ${JSON.stringify({
    testVersion: String(test.testVersion || TEST_VERSION), questionSignature: signature(test),
    questions: test.questions.map(question => [String(question.id), question.options.length, question.type === 'ranking' ? 1 : 0])
  })}`);
  return '// Generated by node scripts/update-draft-manifest.cjs. No question text or answers.\nmodule.exports = {\n' + entries.join(',\n') + '\n};\n';
}
function checkManifest() { return fs.existsSync(target) && fs.readFileSync(target, 'utf8') === manifestContents(); }
function writeManifest() { fs.writeFileSync(target, manifestContents()); }
if (require.main === module) {
  if (process.argv.includes('--check')) {
    if (!checkManifest()) {
      console.error('Draft metadata changed. Run node scripts/update-draft-manifest.cjs.');
      process.exitCode = 1;
    } else console.log('Draft metadata matches the current questionnaires.');
  } else { writeManifest(); console.log('Updated draft metadata.'); }
}
module.exports = { manifestContents, checkManifest, writeManifest };
